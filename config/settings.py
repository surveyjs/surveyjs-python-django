# SQLite through the ORM. WAL lets readers work while one request writes; IMMEDIATE takes the write lock when a
# transaction starts, so two concurrent upserts of one key wait for each other instead of failing. Every
# connection closes at the end of its request (CONN_MAX_AGE 0): Windows can't delete a visitor's sandbox file
# while a connection still holds it.
