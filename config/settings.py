@cache
def _generated_secret_key():
    """A random key kept on the data volume, written the first time Django needs it (so it survives restarts,
    and `manage.py serve` still checks its port before anything is written)."""
    path = DATA_DIR / 'secret_key'
    if not path.is_file():
        path.write_text(get_random_secret_key(), encoding='utf-8')
    return path.read_text(encoding='utf-8').strip()


